class Motor:
    """Jogador automático: Minimax + Alfa-Beta com limite de tempo por jogada."""

    def __init__(self, tempo=10.0, usar_livro=True, nome="IA"):
        self.tempo = max(0.05, min(float(tempo), 110.0))  # nunca passa de 110 s (limite do trabalho: 120 s)
        self.usar_livro = usar_livro
        self.nome = nome
        self.tt = {}
        self.matador = [[0, 0] for _ in range(80)]
        self.historia = [0] * (13 * 120)
        self.nos = 0
        self.stats = []  # (profundidade, tempo gasto) de cada jogada

    # ---------- ordenação ----------
    def _ordenar(self, t, moves, tt_mov, ply):
        b = t.b
        k1, k2 = self.matador[ply]
        hist = self.historia
        pontuados = []
        for m in moves:
            if m == tt_mov:
                s = 10 ** 7
            else:
                o, d, promo = m & 255, (m >> 8) & 255, (m >> 16) & 15
                v = b[d]
                if v or (m >> 20) == F_EP:
                    vit = VAL_ORD[abs(v)] if v else 1
                    s = 1000000 + vit * 100 - VAL_ORD[abs(b[o])]
                elif promo:
                    s = 1100000 if promo == 5 else 500000
                elif m == k1:
                    s = 900000
                elif m == k2:
                    s = 899000
                else:
                    s = hist[(b[o] + 6) * 120 + d]
            pontuados.append((s, m))
        pontuados.sort(reverse=True)
        return [m for _, m in pontuados]

    def _tem_peca_pesada(self, t):
        b, vez = t.b, t.vez
        for sq in CASAS:
            p = b[sq] * vez
            if 2 <= p <= 5:
                return True
        return False

    # ---------- quiescência ----------
    def _quiescencia(self, alfa, beta, ply):
        t = self.t
        self.nos += 1
        if self.pode_abortar and (self.nos & 2047) == 0 and time.perf_counter() > self.limite:
            raise TempoEsgotado
        parado = avaliar(t)
        if ply >= 70:
            return parado
        b = t.b
        if t.vez == BRANCO:
            if parado >= beta:
                return parado
            if parado > alfa:
                alfa = parado
            melhor = parado
            for m in self._ordenar(t, t.gerar(True), 0, ply):
                v = b[(m >> 8) & 255]
                ganho = VALOR[abs(v)] if v else 100
                if (m >> 16) & 15:
                    ganho += 800
                if parado + ganho + 200 < alfa:  # delta pruning
                    continue
                t.faz(m)
                if t.atacada(t.rei[BRANCO], PRETO):
                    t.desfaz()
                    continue
                val = self._quiescencia(alfa, beta, ply + 1)
                t.desfaz()
                if val > melhor:
                    melhor = val
                    if val > alfa:
                        alfa = val
                        if alfa >= beta:
                            break
            return melhor
        else:
            if parado <= alfa:
                return parado
            if parado < beta:
                beta = parado
            melhor = parado
            for m in self._ordenar(t, t.gerar(True), 0, ply):
                v = b[(m >> 8) & 255]
                ganho = VALOR[abs(v)] if v else 100
                if (m >> 16) & 15:
                    ganho += 800
                if parado - ganho - 200 > beta:
                    continue
                t.faz(m)
                if t.atacada(t.rei[PRETO], BRANCO):
                    t.desfaz()
                    continue
                val = self._quiescencia(alfa, beta, ply + 1)
                t.desfaz()
                if val < melhor:
                    melhor = val
                    if val < beta:
                        beta = val
                        if alfa >= beta:
                            break
            return melhor

    # ---------- Minimax com Alfa-Beta ----------
    def _minimax(self, prof, alfa, beta, ply, nulo_ok):
        t = self.t
        self.nos += 1
        if self.pode_abortar and (self.nos & 2047) == 0 and time.perf_counter() > self.limite:
            raise TempoEsgotado
        if ply > 0 and (t.meio >= 100 or t.repetida()):
            return 0
        maximiza = t.vez == BRANCO
        em_xeque = t.em_xeque()
        if em_xeque and ply < 60:
            prof += 1
        if prof <= 0 or ply >= 70:
            return self._quiescencia(alfa, beta, ply)

        alfa0, beta0 = alfa, beta
        tt_mov = 0
        ent = self.tt.get(t.h)
        if ent:
            d_e, flag, val, tt_mov = ent
            if d_e >= prof and ply > 0:
                if val > MATE_LIM:
                    val -= ply
                elif val < -MATE_LIM:
                    val += ply
                if flag == 0:
                    return val
                if flag == 1:
                    if val > alfa:
                        alfa = val
                elif val < beta:
                    beta = val
                if alfa >= beta:
                    return val

        # null move: se até passando a vez eu já corto, nem precisa olhar os lances
        if nulo_ok and not em_xeque and prof >= 3 and ply > 0 and self._tem_peca_pesada(t):
            t.faz_nulo()
            try:
                if maximiza:
                    v = self._minimax(prof - 3, beta - 1, beta, ply + 1, False)
                else:
                    v = self._minimax(prof - 3, alfa, alfa + 1, ply + 1, False)
            finally:
                t.desfaz()
            if maximiza and v >= beta:
                return beta if abs(v) > MATE_LIM else v
            if not maximiza and v <= alfa:
                return alfa if abs(v) > MATE_LIM else v

        moves = self._ordenar(t, t.gerar(), tt_mov, ply)
        b = t.b
        legais = 0
        melhor_m = 0
        k1, k2 = self.matador[ply]
        if maximiza:
            melhor = -INF
            for m in moves:
                d = (m >> 8) & 255
                quieto = b[d] == 0 and not (m >> 16) & 15 and (m >> 20) != F_EP
                o = m & 255
                peca = b[o]
                t.faz(m)
                if t.atacada(t.rei[BRANCO], PRETO):
                    t.desfaz()
                    continue
                legais += 1
                if legais > 4 and prof >= 3 and quieto and not em_xeque and m != k1 and m != k2:
                    v = self._minimax(prof - 2, alfa, alfa + 1, ply + 1, True)
                    if v > alfa:
                        v = self._minimax(prof - 1, alfa, beta, ply + 1, True)
                else:
                    v = self._minimax(prof - 1, alfa, beta, ply + 1, True)
                t.desfaz()
                if v > melhor:
                    melhor, melhor_m = v, m
                    if ply == 0:
                        self.raiz_mov, self.raiz_val = m, v
                    if v > alfa:
                        alfa = v
                        if alfa >= beta:
                            if quieto:
                                self._registra_corte(m, peca, d, prof, ply)
                            break
        else:
            melhor = INF
            for m in moves:
                d = (m >> 8) & 255
                quieto = b[d] == 0 and not (m >> 16) & 15 and (m >> 20) != F_EP
                o = m & 255
                peca = b[o]
                t.faz(m)
                if t.atacada(t.rei[PRETO], BRANCO):
                    t.desfaz()
                    continue
                legais += 1
                if legais > 4 and prof >= 3 and quieto and not em_xeque and m != k1 and m != k2:
                    v = self._minimax(prof - 2, beta - 1, beta, ply + 1, True)
                    if v < beta:
                        v = self._minimax(prof - 1, alfa, beta, ply + 1, True)
                else:
                    v = self._minimax(prof - 1, alfa, beta, ply + 1, True)
                t.desfaz()
                if v < melhor:
                    melhor, melhor_m = v, m
                    if ply == 0:
                        self.raiz_mov, self.raiz_val = m, v
                    if v < beta:
                        beta = v
                        if alfa >= beta:
                            if quieto:
                                self._registra_corte(m, peca, d, prof, ply)
                            break

        if legais == 0:
            if em_xeque:
                return -(MATE - ply) if maximiza else (MATE - ply)
            return 0

        if melhor <= alfa0:
            flag = 2
        elif melhor >= beta0:
            flag = 1
        else:
            flag = 0
        val = melhor
        if val > MATE_LIM:
            val += ply
        elif val < -MATE_LIM:
            val -= ply
        self.tt[t.h] = (prof, flag, val, melhor_m)
        return melhor

    def _registra_corte(self, m, peca, destino, prof, ply):
        k = self.matador[ply]
        if k[0] != m:
            k[1] = k[0]
            k[0] = m
        i = (peca + 6) * 120 + destino
        self.historia[i] = min(self.historia[i] + prof * prof, 800000)

    # ---------- escolha da jogada (aprofundamento iterativo) ----------
    def escolher(self, tab):
        """Recebe um Tabuleiro e devolve (lance, info). O tabuleiro original não é alterado."""
        ini = time.perf_counter()
        info = {"profundidade": 0, "nos": 0, "valor": 0, "livro": False, "tempo": 0.0}
        legais = tab.legais()
        if not legais:
            return None, info
        if len(legais) == 1:
            info["tempo"] = time.perf_counter() - ini
            return legais[0], info
        if self.usar_livro and tab.h in LIVRO:
            opcoes = [m for m in LIVRO[tab.h] if m in legais]
            if opcoes:
                info["livro"] = True
                info["tempo"] = time.perf_counter() - ini
                return random.choice(opcoes), info

        self.t = tab.copiar()
        self.limite = ini + self.tempo
        self.nos = 0
        if len(self.tt) > 1500000:
            self.tt.clear()
        self.historia = [x // 4 for x in self.historia]
        self.matador = [[0, 0] for _ in range(80)]
        melhor = legais[0]
        valor = 0
        prof_ok = 0
        for prof in range(1, 64):
            self.pode_abortar = prof > 1  # a profundidade 1 sempre termina
            self.raiz_mov = 0
            try:
                v = self._minimax(prof, -INF, INF, 0, False)
            except TempoEsgotado:
                break
            if self.raiz_mov:
                melhor, valor, prof_ok = self.raiz_mov, v, prof
            if abs(v) > MATE_LIM:
                break
            if time.perf_counter() - ini > self.tempo * 0.4:
                break  # a próxima profundidade provavelmente não termina a tempo
        info.update(profundidade=prof_ok, nos=self.nos, valor=valor,
                    tempo=time.perf_counter() - ini)
        self.stats.append((prof_ok, info["tempo"]))
        return melhor, info


