def motivo_ilegal(t, o, d):
    """Explica por que o lance origem->destino não pode ser feito."""
    p = t.b[o]
    if p == 0:
        return "não há nenhuma peça em %s." % nome_casa(o)
    if p * t.vez < 0:
        return "a peça em %s é do adversário." % nome_casa(o)
    pseudo = [m for m in t.gerar() if m & 255 == o and (m >> 8) & 255 == d]
    if pseudo:
        if t.em_xeque():
            return "seu rei está em xeque e esse lance não resolve."
        return "esse lance deixaria seu rei em xeque (ou o rei passaria por uma casa atacada)."
    if t.b[d] != 0 and t.b[d] * t.vez > 0:
        return "a casa %s já tem uma peça sua." % nome_casa(d)
    return "o %s não anda de %s para %s." % (NOMES_PT[abs(p)], nome_casa(o), nome_casa(d))


def interpretar(t, texto, perguntar=input):
    """Transforma o que o usuário digitou em um lance legal. Retorna (lance, mensagem_de_erro)."""
    legais = t.legais()
    s = texto.strip().replace(" ", "").replace("-", "").replace("–", "")
    if not s:
        return None, "digite um lance (ou 'ajuda')."
    if s.upper().replace("0", "O") in ("OO", "OOO"):
        curto = s.upper().replace("0", "O") == "OO"
        for m in legais:
            if (m >> 20) == F_ROQUE and (((m >> 8) & 255) > (m & 255)) == curto:
                return m, None
        return None, "o roque %s não é possível agora." % ("curto" if curto else "longo")
    mapa_promo = {"q": 5, "d": 5, "r": 4, "t": 4, "b": 3, "n": 2, "c": 2}
    mt = re.fullmatch(r"([a-h][1-8])([a-h][1-8])([qdrtbnc]?)", s.lower())
    if mt:
        o, d = casa_de_nome(mt.group(1)), casa_de_nome(mt.group(2))
        cands = [m for m in legais if m & 255 == o and (m >> 8) & 255 == d]
        if not cands:
            return None, "lance ilegal: " + motivo_ilegal(t, o, d)
        if len(cands) == 1:
            return cands[0], None
        promo = mapa_promo.get(mt.group(3), 0)
        while not promo:
            r = perguntar("Promover para qual peça? (d = dama, t = torre, b = bispo, c = cavalo): ").strip().lower()
            promo = mapa_promo.get(r[:1], 0)
        for m in cands:
            if (m >> 16) & 15 == promo:
                return m, None
    # notação algébrica (SAN)
    def norm(x):
        return x.replace("x", "").replace("+", "").replace("#", "").replace("!", "").replace("?", "").replace("=", "")
    alvo = norm(s)
    for m in legais:
        san = norm(t.para_san(m))
        if alvo == san or (alvo[:1] in "nrqk" and alvo[:1].upper() + alvo[1:] == san):
            return m, None
    return None, "não entendi esse lance. Exemplos: e2e4, g1f3, Nf3, exd5, O-O, e7e8q."


