    tudo_ok = True
    for nome, fen, esperado in TESTES_PERFT:
        t = Tabuleiro(fen)
        obtido = []
        t0 = time.perf_counter()
        for i in range(len(esperado)):
            obtido.append(perft(t, i + 1))
        ok = obtido == esperado
        tudo_ok &= ok
        print("%-30s %s  (%.1fs)" % (nome, "OK" if ok else "ERRO", time.perf_counter() - t0))
        if not ok:
            print("   esperado:", esperado, "obtido:", obtido)
        # o tabuleiro tem que voltar exatamente ao que era (hash e FEN iguais)
        assert t.para_fen() == Tabuleiro(fen).para_fen() and t.h == t.calcular_hash()
    print("\nTodas as regras conferem com os valores oficiais!" if tudo_ok else "\nTem erro nas regras, revisar!")
    return tudo_ok


