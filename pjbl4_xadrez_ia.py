"""## 7. Partida automática IA x IA

Esta função faz o papel de árbitro: ela chama cada motor na sua vez, confere se o lance é legal, mede o tempo e aplica as regras de derrota automática do enunciado (lance ilegal ou mais de 2 minutos). Também deu pra usar para testar a estabilidade do sistema e para simular a competição entre dois motores.
"""

LIMITE_TEMPO_OFICIAL = 120.0


def partida_automatica(motor_brancas, motor_pretas, fen=None, max_lances=250, mostrar=True):
    t = Tabuleiro(fen)
    motores = {BRANCO: motor_brancas, PRETO: motor_pretas}
    lances_san = []
    tempos = {BRANCO: [], PRETO: []}
    profs = {BRANCO: [], PRETO: []}
    while True:
        r = t.resultado()
        if r:
            codigo, venc, texto = r
            break
        if len(lances_san) >= 2 * max_lances:
            codigo, venc, texto = "limite", 0, "Empate: limite de lances da simulação."
            break
        cor = t.vez
        ini = time.perf_counter()
        try:
            m, info = motores[cor].escolher(t)
        except Exception as e:  # erro do motor = derrota
            codigo, venc, texto = "erro", -cor, "Derrota automática: o motor travou (%s)." % e
            break
        gasto = time.perf_counter() - ini
        if gasto > LIMITE_TEMPO_OFICIAL:
            codigo, venc, texto = "tempo", -cor, "Derrota automática por tempo."
            break
        if m not in t.legais():
            codigo, venc, texto = "ilegal", -cor, "Derrota automática por lance ilegal."
            break
        san = t.para_san(m)
        if cor == BRANCO:
            san = "%d. %s" % (t.num, san)
        lances_san.append(san)
        tempos[cor].append(gasto)
        profs[cor].append(info["profundidade"])
        t.faz(m)
    if mostrar:
        print(" ".join(lances_san))
        print("\n" + texto)
        for cor, nome in ((BRANCO, "Brancas"), (PRETO, "Pretas")):
            if tempos[cor]:
                print("%s: tempo médio %.2fs, maior %.2fs, profundidade média %.1f" % (
                    nome, sum(tempos[cor]) / len(tempos[cor]), max(tempos[cor]),
                    sum(profs[cor]) / max(1, len(profs[cor]))))
    return {"resultado": codigo, "vencedor": venc, "texto": texto, "lances": lances_san,
            "tempo_max": {c: max(tempos[c]) if tempos[c] else 0 for c in tempos}}


def torneio(motores, mostrar=True):
    """Todos contra todos, dois jogos por confronto (um com cada cor). Vitória 1, empate 0,5."""
    pontos = {m.nome: 0.0 for m in motores}
    for i, a in enumerate(motores):
        for b_ in motores[i + 1:]:
            for brancas, pretas in ((a, b_), (b_, a)):
                res = partida_automatica(brancas, pretas, mostrar=False)
                if res["vencedor"] == BRANCO:
                    pontos[brancas.nome] += 1
                elif res["vencedor"] == PRETO:
                    pontos[pretas.nome] += 1
                else:
                    pontos[brancas.nome] += 0.5
                    pontos[pretas.nome] += 0.5
                if mostrar:
                    print("%s (B) x %s (P): %s" % (brancas.nome, pretas.nome, res["texto"]))
    return pontos

