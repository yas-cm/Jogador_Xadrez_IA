BONUS_PASSADO = [0, 5, 10, 20, 35, 60, 100, 0]  # indexado pela fileira (0 = 1ª) vista do dono


def avaliar(t):
    """Avaliação estática em centipeões, do ponto de vista das brancas."""
    b = t.b
    mg = eg = 0
    fase = 0
    bispos_b = bispos_p = 0
    pesadas = 0
    mat_b = mat_p = 0
    # peões por coluna (índice = coluna + 1; as pontas 0 e 9 são sentinelas)
    cont_b = [0] * 10
    cont_p = [0] * 10
    max_lin_p = [-1] * 10   # maior fileira de peão preto na coluna
    min_lin_b = [8] * 10    # menor fileira de peão branco na coluna
    peoes_b = []
    peoes_p = []
    torres_b = []
    torres_p = []
    mob_mg = mob_eg = 0

    for sq in CASAS:
        p = b[sq]
        if p == 0:
            continue
        mg += PST_MEIO[p + 6][sq]
        eg += PST_FIM[p + 6][sq]
        t_ = p if p > 0 else -p
        if t_ == PEAO:
            col = (sq - 21) % 10 + 1
            lin = 7 - (sq - 21) // 10
            if p > 0:
                cont_b[col] += 1
                peoes_b.append((col, lin))
                if lin < min_lin_b[col]:
                    min_lin_b[col] = lin
            else:
                cont_p[col] += 1
                peoes_p.append((col, lin))
                if lin > max_lin_p[col]:
                    max_lin_p[col] = lin
            continue
        if t_ == REI:
            continue
        sinal = 1 if p > 0 else -1
        if sinal > 0:
            mat_b += VALOR[t_]
        else:
            mat_p += VALOR[t_]
        if t_ == CAVALO:
            fase += 1
            n = 0
            for d in DIR_CAVALO:
                c = b[sq + d]
                if c == 0 or (c != FORA and c * p < 0):
                    n += 1
            mob_mg += sinal * (n - 4) * 4
            mob_eg += sinal * (n - 4) * 4
        elif t_ == BISPO:
            fase += 1
            if sinal > 0:
                bispos_b += 1
            else:
                bispos_p += 1
            n = 0
            for d in DIR_DIAG:
                s = sq + d
                while b[s] == 0:
                    n += 1
                    s += d
                if b[s] != FORA and b[s] * p < 0:
                    n += 1
            mob_mg += sinal * (n - 6) * 3
            mob_eg += sinal * (n - 6) * 4
        elif t_ == TORRE:
            fase += 2
            pesadas += 1
            (torres_b if sinal > 0 else torres_p).append((sq - 21) % 10 + 1)
            n = 0
            for d in DIR_RETA:
                s = sq + d
                while b[s] == 0:
                    n += 1
                    s += d
                if b[s] != FORA and b[s] * p < 0:
                    n += 1
            mob_mg += sinal * (n - 7) * 2
            mob_eg += sinal * (n - 7) * 4
        else:  # dama
            fase += 4
            pesadas += 1

    # material insuficiente = empate
    if not peoes_b and not peoes_p and pesadas == 0 and (mat_b + mat_p) <= 330:
        return 0

    mg += mob_mg
    eg += mob_eg

    # par de bispos
    if bispos_b >= 2:
        mg += 30
        eg += 45
    if bispos_p >= 2:
        mg -= 30
        eg -= 45

    # estrutura de peões
    for col, lin in peoes_b:
        if cont_b[col] > 1:
            mg -= 10
            eg -= 15
        if cont_b[col - 1] == 0 and cont_b[col + 1] == 0:
            mg -= 12
            eg -= 15
        if max_lin_p[col - 1] <= lin and max_lin_p[col] <= lin and max_lin_p[col + 1] <= lin:
            mg += BONUS_PASSADO[lin] // 2
            eg += BONUS_PASSADO[lin]
    for col, lin in peoes_p:
        if cont_p[col] > 1:
            mg += 10
            eg += 15
        if cont_p[col - 1] == 0 and cont_p[col + 1] == 0:
            mg += 12
            eg += 15
        if min_lin_b[col - 1] >= lin and min_lin_b[col] >= lin and min_lin_b[col + 1] >= lin:
            mg -= BONUS_PASSADO[7 - lin] // 2
            eg -= BONUS_PASSADO[7 - lin]

    # torres em colunas abertas
    for col in torres_b:
        if cont_b[col] == 0:
            bonus = 20 if cont_p[col] == 0 else 10
            mg += bonus
            eg += bonus
    for col in torres_p:
        if cont_p[col] == 0:
            bonus = 20 if cont_b[col] == 0 else 10
            mg -= bonus
            eg -= bonus

    # segurança do rei: escudo de peões (só vale no meio-jogo)
    rb, rp = t.rei[BRANCO], t.rei[PRETO]
    if rb >= 81:
        esc = 0
        for dc in (-1, 0, 1):
            if b[rb - 10 + dc] == PEAO:
                esc += 10
            elif b[rb - 20 + dc] == PEAO:
                esc += 5
            else:
                esc -= 10
        mg += esc
    if rp <= 38:
        esc = 0
        for dc in (-1, 0, 1):
            if b[rp + 10 + dc] == -PEAO:
                esc += 10
            elif b[rp + 20 + dc] == -PEAO:
                esc += 5
            else:
                esc -= 10
        mg -= esc

    if fase > 24:
        fase = 24

    # final ganho: encurralar o rei adversário (necessário para dar mate)
    dif = mat_b - mat_p
    if fase <= 12 and (dif >= 300 or dif <= -300):
        if dif > 0:
            perdedor, vencedor, sinal = rp, rb, 1
        else:
            perdedor, vencedor, sinal = rb, rp, -1
        lp, cp = (perdedor - 21) // 10, (perdedor - 21) % 10
        lv, cv = (vencedor - 21) // 10, (vencedor - 21) % 10
        dist_centro = max(3 - cp, cp - 4) + max(3 - lp, lp - 4)
        dist_reis = abs(lp - lv) + abs(cp - cv)
        eg += sinal * (dist_centro * 12 + (14 - dist_reis) * 5)

    return (mg * fase + eg * (24 - fase)) // 24

"""## 4. Busca: Minimax com poda Alfa-Beta

A busca está escrita no formato Minimax "explícito": quando é a vez das brancas o nó **maximiza** a avaliação e quando é a vez das pretas ele **minimiza**. `alfa` é o melhor valor que o maximizador já tem garantido e `beta` o melhor que o minimizador já tem garantido. Se `alfa >= beta` o resto dos lances daquele nó não precisa ser visto (poda).

Melhorias que colocamos em cima do Minimax básico, para chegar numa profundidade maior no mesmo tempo:

- **Aprofundamento iterativo**: busca profundidade 1, depois 2, 3... e guarda o melhor lance da última profundidade completa. Se o relógio estoura no meio de uma profundidade, a gente descarta ela e usa o lance da anterior. É isso que garante o limite de tempo.
- **Tabela de transposição** (Zobrist): lembra posições já avaliadas e o melhor lance de cada uma.
- **Ordenação de lances**: primeiro o lance da tabela, depois capturas boas (MVV-LVA), promoções, lances "killer" e heurística de histórico. Quanto melhor a ordem, mais a poda corta.
- **Busca de quiescência**: no fim da profundidade continua só com capturas para não avaliar posição no meio de uma troca.
- **Extensão de xeque**: quando está em xeque, busca um nível a mais.
- **Null move pruning** e **LMR** (reduzir a profundidade dos lances quietos tardios, com re-busca se parecerem bons).
- **Livro de aberturas** pequeno, para as primeiras jogadas saírem na hora e com variedade.
"""

